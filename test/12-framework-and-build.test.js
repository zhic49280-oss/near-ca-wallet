'use strict';

const { test, assert, fs, path, ROOT_DIR } = require('./helpers.js');

test('v6.41-v6.44 Architecture: Vite+Preact framework bundle, esbuild minification, part size limits & CI npm ci', () => {
  // 1. Vite + Preact framework bundle exists and is synced
  const fwRoot = path.join(ROOT_DIR, 'src', 'framework-ui.js');
  const fwDist = path.join(ROOT_DIR, 'dist', 'src', 'framework-ui.js');
  assert.ok(fs.existsSync(fwRoot), 'src/framework-ui.js must be generated by Vite');
  assert.ok(fs.existsSync(fwDist), 'dist/src/framework-ui.js must be synced');
  const fwSrc = fs.readFileSync(fwRoot, 'utf8');
  assert.ok(fwSrc.includes('NearCAFramework') || fwSrc.includes('mountSwapHistory'), 'framework-ui.js must expose NearCAFramework');

  // 2. Production minification saves >= 30% on dist/src/ui-controller.js
  const rawUiSize = fs.statSync(path.join(ROOT_DIR, 'src', 'ui-controller.js')).size;
  const minUiSize = fs.statSync(path.join(ROOT_DIR, 'dist', 'src', 'ui-controller.js')).size;
  assert.ok(minUiSize < rawUiSize * 0.7, `dist/src/ui-controller.js (${minUiSize}) must be at least 30% smaller than root (${rawUiSize})`);

  // 3. Every ui-controller part is <= 60 KB
  const uiPartsDir = path.join(ROOT_DIR, 'src', 'parts', 'ui-controller');
  for (const fname of fs.readdirSync(uiPartsDir).filter((n) => n.endsWith('.part.js'))) {
    const sz = fs.statSync(path.join(uiPartsDir, fname)).size;
    assert.ok(sz <= 60 * 1024, `ui-controller/${fname} (${(sz / 1024).toFixed(1)}KB) exceeds 60KB limit`);
  }

  // 4. 240-lifecycle.part.js has zero duplicate keys in NearCAUI and globalHandlers
  const lifecycleSrc = fs.readFileSync(path.join(uiPartsDir, '240-lifecycle.part.js'), 'utf8');
  for (const objName of ['NearCAUI', 'globalHandlers']) {
    const m = lifecycleSrc.match(new RegExp(`const ${objName} = \\{([\\s\\S]*?)\\n  \\};`));
    assert.ok(m, `${objName} block must exist in 240-lifecycle.part.js`);
    const keys = m[1].split(/\r?\n/).map((l) => l.trim().replace(/,$/, '')).filter(Boolean);
    const seen = new Set();
    for (const k of keys) {
      assert.equal(seen.has(k), false, `Duplicate key "${k}" found in ${objName}`);
      seen.add(k);
    }
  }

  // 5. GitHub Actions CI workflows install devDependencies before npm run build
  for (const wf of ['build-android-apk.yml', 'build-ios-ipa.yml']) {
    const wfSrc = fs.readFileSync(path.join(ROOT_DIR, '.github', 'workflows', wf), 'utf8');
    const ciIdx = wfSrc.indexOf('npm ci');
    const buildIdx = wfSrc.indexOf('npm run build');
    assert.ok(ciIdx > 0 && buildIdx > ciIdx, `${wf} must run npm ci before npm run build`);
  }
});
